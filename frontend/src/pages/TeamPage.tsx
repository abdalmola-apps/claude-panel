import { useEffect, useMemo, useState } from "react";
import { api } from "../lib/api";
import { useStore } from "../lib/store";
import { Card, Select } from "../components/ui";
import type { Agent, Project } from "../lib/types";

interface Role { key: string; title: string; agent: string; instruction: string; }

const DEFAULT_ROLES: Role[] = [
  { key: "analyst", title: "Business Analyst", agent: "", instruction: "Analyze the request: define the scope, goals, and clear, numbered acceptance criteria. At sign-off, decide whether the delivered product meets them." },
  { key: "requirements", title: "Requirements", agent: "", instruction: "Turn the analysis into concrete, testable, numbered requirements — no ambiguity, each independently verifiable." },
  { key: "developer", title: "Developer", agent: "", instruction: "Implement the requirements with focused diffs, following the project's existing conventions. Address any feedback from the previous cycle." },
  { key: "qa", title: "QA Tester", agent: "", instruction: "Test the implementation against every requirement. Report pass/fail with the specific failing cases and steps to reproduce." },
  { key: "reviewer", title: "Reviewer", agent: "", instruction: "Review the implementation and the QA report for correctness and quality. Approve, or list the exact changes still needed." },
];

const S = (s: string) => JSON.stringify(s || "");

function buildWorkflow(name: string, task: string, maxCycles: number, roles: Role[]): string {
  const by = Object.fromEntries(roles.map((r) => [r.key, r])) as Record<string, Role>;
  const at = (r: Role) => (r.agent ? `, agentType: ${S(r.agent)}` : "");
  const ba = by.analyst, req = by.requirements, dev = by.developer, qa = by.qa, rev = by.reviewer;
  const mc = Math.max(1, Math.min(20, maxCycles | 0)) || 3;
  return `export const meta = {
  name: ${S(name)},
  description: ${S("Software-team pipeline: BA → requirements → dev → QA → review, recycling until the analyst signs off.")},
  phases: [
    { title: 'Analysis' },
    { title: 'Requirements' },
    { title: 'Development' },
    { title: 'QA' },
    { title: 'Review' },
    { title: 'Sign-off' },
  ],
}

// Generated by Claude Control — Team builder.
// Run it in a Claude Code session in this project: open /workflows, or ask
// Claude to run the "${name}" workflow. Override the brief with args.task.

const TASK = (args && args.task) || ${S(task)}
const MAX_CYCLES = ${mc}

const QA = { type: 'object', properties: { passed: { type: 'boolean' }, issues: { type: 'string' } }, required: ['passed'] }
const REVIEW = { type: 'object', properties: { approved: { type: 'boolean' }, changes: { type: 'string' } }, required: ['approved'] }
const SIGNOFF = { type: 'object', properties: { approved: { type: 'boolean' }, reason: { type: 'string' } }, required: ['approved'] }

phase('Analysis')
const analysis = await agent(
  ${S(ba.instruction)} + "\\n\\n## Request\\n" + TASK,
  { label: 'BA: analysis', phase: 'Analysis'${at(ba)} }
)

phase('Requirements')
const requirements = await agent(
  ${S(req.instruction)} + "\\n\\n## Analysis\\n" + analysis,
  { label: 'requirements', phase: 'Requirements'${at(req)} }
)

let cycle = 0, feedback = '', qa, review, build
while (cycle < MAX_CYCLES) {
  cycle++
  phase('Development')
  build = await agent(
    ${S(dev.instruction)} + "\\n\\n## Requirements\\n" + requirements + (feedback ? "\\n\\n## Fix this feedback from the last cycle\\n" + feedback : ''),
    { label: 'dev: cycle ' + cycle, phase: 'Development'${at(dev)} }
  )
  phase('QA')
  qa = await agent(
    ${S(qa.instruction)} + "\\n\\n## Requirements\\n" + requirements + "\\n\\n## What was built\\n" + build,
    { label: 'QA: cycle ' + cycle, phase: 'QA'${at(qa)}, schema: QA }
  )
  phase('Review')
  review = await agent(
    ${S(rev.instruction)} + "\\n\\n## What was built\\n" + build + "\\n\\n## QA report\\n" + JSON.stringify(qa),
    { label: 'review: cycle ' + cycle, phase: 'Review'${at(rev)}, schema: REVIEW }
  )
  if (qa.passed && review.approved) { log('Cycle ' + cycle + ': QA + review passed.'); break }
  feedback = [qa.issues, review.changes].filter(Boolean).join('\\n')
  log('Cycle ' + cycle + ': not approved yet — recycling.')
}

phase('Sign-off')
const signoff = await agent(
  ${S(ba.instruction)} + "\\n\\n## Acceptance criteria (from your own analysis)\\n" + analysis + "\\n\\n## Delivered\\n" + build + "\\n\\nApprove for deploy ONLY if the acceptance criteria are met; otherwise set approved false and explain what is missing.",
  { label: 'BA: sign-off', phase: 'Sign-off'${at(ba)}, schema: SIGNOFF }
)

return { task: TASK, cycles: cycle, approved: !!signoff.approved, signoff, qa, review }
`;
}

export function TeamPage() {
  const { toast } = useStore();
  const [projects, setProjects] = useState<Project[]>([]);
  const [proj, setProj] = useState<string>(""); // claudeDir of selected project ("" = global)
  const [agents, setAgents] = useState<Agent[]>([]);
  const [name, setName] = useState("product-team");
  const [task, setTask] = useState("");
  const [maxCycles, setMaxCycles] = useState(3);
  const [roles, setRoles] = useState<Role[]>(DEFAULT_ROLES.map((r) => ({ ...r })));
  const [script, setScript] = useState("");
  const [saving, setSaving] = useState(false);

  useEffect(() => { api.projects().then((r) => setProjects(r.projects)).catch(() => {}); }, []);
  useEffect(() => { api.listAgents().then((r) => setAgents(r.agents)).catch(() => {}); }, []);

  const agentNames = useMemo(() => agents.map((a) => a.name), [agents]);
  const current = projects.find((p) => (p.isGlobal ? proj === "" : p.claudeDir === proj));

  const setRole = (i: number, patch: Partial<Role>) =>
    setRoles((rs) => rs.map((r, j) => (j === i ? { ...r, ...patch } : r)));

  const generate = () => {
    if (!/^[a-z0-9][a-z0-9_-]*$/.test(name)) { toast("Name must be a lowercase slug", "err"); return; }
    setScript(buildWorkflow(name, task, maxCycles, roles));
  };

  const save = async () => {
    if (!script) return;
    setSaving(true);
    try {
      const r = await api.saveWorkflow(name, script, proj || undefined);
      toast(`Saved to ${r.path}${r.backup ? " (previous backed up)" : ""}`, "ok");
    } catch (e: any) { toast("Save failed: " + (e.message || e), "err"); }
    finally { setSaving(false); }
  };

  return (
    <div className="main-inner" style={{ maxWidth: 960 }}>
      <div className="page-head">
        <h1>Team Pipeline</h1>
        <p>
          Assemble your roster into a software team that runs a product end to end — <b>Business Analyst → Requirements →
          Developer → QA → Reviewer</b>, recycling the build&nbsp;↔&nbsp;QA&nbsp;↔&nbsp;review loop until it passes and the analyst
          signs off. This generates a real Claude Code <b>Workflow</b>; run it in a session and <a href="#" onClick={(e) => e.preventDefault()} style={{ color: "var(--accent)", cursor: "default" }}>Who&rsquo;s Working</a> shows the phases live.
        </p>
      </div>

      <Card title="Pipeline">
        <div className="form-grid">
          <div className="field">
            <label>Save to project</label>
            <select className="scope-select" style={{ marginInlineStart: 0, width: "100%" }} value={proj} onChange={(e) => setProj(e.target.value)}>
              {projects.map((p) => (
                <option key={p.id} value={p.isGlobal ? "" : p.claudeDir}>{(p.isGlobal ? "● " : "  ") + p.label}</option>
              ))}
            </select>
          </div>
          <div className="field">
            <label>Workflow name</label>
            <input className="input-sm mono" value={name} onChange={(e) => setName(e.target.value.toLowerCase())} placeholder="product-team" />
          </div>
        </div>
        <div className="field">
          <label>The brief <span style={{ color: "var(--muted)", fontWeight: 400 }}>— what the team should build (also overridable at run time via args.task)</span></label>
          <textarea rows={3} value={task} onChange={(e) => setTask(e.target.value)} placeholder="e.g. Add a leave-request approval flow to the HR module with manager + HR sign-off and a Slack notification." />
        </div>
        <div className="field" style={{ maxWidth: 220 }}>
          <label>Max build↔review cycles</label>
          <input type="number" min={1} max={20} className="input-sm" style={{ width: 90 }} value={maxCycles} onChange={(e) => setMaxCycles(parseInt(e.target.value, 10) || 1)} />
        </div>
      </Card>

      <Card title="Roles" sub="assign a teammate to each; leave on default to use a general worker">
        {roles.map((r, i) => (
          <div key={r.key} style={{ padding: "12px 0", borderBottom: "1px solid var(--border)" }}>
            <div style={{ display: "flex", gap: 10, alignItems: "center", marginBottom: 8, flexWrap: "wrap" }}>
              <input className="input-sm" style={{ fontWeight: 600, width: 180 }} value={r.title} onChange={(e) => setRole(i, { title: e.target.value })} />
              <span style={{ color: "var(--muted)", fontSize: 12 }}>played by</span>
              <Select value={r.agent} options={agentNames} allowEmpty="(default worker)" onChange={(v) => setRole(i, { agent: v })} />
              {r.agent && !agentNames.includes(r.agent) && <span className="badge ask" style={{ fontSize: 10 }}>unknown agent</span>}
            </div>
            <textarea rows={2} value={r.instruction} onChange={(e) => setRole(i, { instruction: e.target.value })} style={{ fontSize: 12.5 }} />
          </div>
        ))}
      </Card>

      <div style={{ display: "flex", gap: 8, margin: "4px 0 14px" }}>
        <button className="btn primary" onClick={generate}>Generate workflow</button>
        {script && <button className="btn" disabled={saving} onClick={save}>{saving ? "Saving…" : "Save to .claude/workflows/"}</button>}
      </div>

      {script && (
        <Card
          title="Generated workflow"
          sub={`${name}.js`}
          right={<button className="btn ghost sm" onClick={() => { navigator.clipboard?.writeText(script).then(() => toast("Copied", "ok"), () => {}); }}>Copy</button>}
        >
          <textarea rows={18} className="mono" value={script} onChange={(e) => setScript(e.target.value)} spellCheck={false} style={{ fontSize: 11.5, lineHeight: 1.5 }} />
          <div className="hint" style={{ marginTop: 8 }}>
            Saves to <code className="mono">{current?.isGlobal ? "~/.claude" : (current?.claudeDir || proj || "~/.claude")}/workflows/{name}.js</code>.
            Then, in a Claude Code session in that project: open <code className="mono">/workflows</code>, or tell Claude to run the <b>{name}</b> workflow — pass a different brief with <code className="mono">args.task</code>. Review it before running; it fans out real subagents.
          </div>
        </Card>
      )}
    </div>
  );
}
