import { useCallback, useEffect, useMemo, useState } from "react";
import { api } from "../lib/api";
import { useStore } from "../lib/store";
import { Card, Select, useConfirm } from "../components/ui";
import { PipelineGraph } from "../components/PipelineGraph";
import type { Agent, Project } from "../lib/types";

type RoleType = "plan" | "build" | "check" | "signoff";
interface Role { key: string; title: string; agent: string; instruction: string; enabled: boolean; type: RoleType; }

export const ROLE_TYPES: { value: RoleType; label: string; hint: string }[] = [
  { value: "plan", label: "Plan", hint: "runs once, before the loop" },
  { value: "build", label: "Build", hint: "produces work inside the recycle loop" },
  { value: "check", label: "Check", hint: "reviews in the loop; can send it back" },
  { value: "signoff", label: "Sign-off", hint: "final approval, after the loop" },
];

const DEFAULT_ROLES: Role[] = [
  { key: "analyst", title: "Business Analyst", agent: "", type: "plan", enabled: true, instruction: "Analyze the request: define the scope, goals, and clear, numbered acceptance criteria." },
  { key: "requirements", title: "Requirements", agent: "", type: "plan", enabled: true, instruction: "Turn the analysis into concrete, testable, numbered requirements — no ambiguity, each independently verifiable." },
  { key: "uiux", title: "UI/UX Designer", agent: "ui-ux-designer", type: "build", enabled: true, instruction: "Design the UI/UX for the requirements: layout, flow, states and tokens. Treat RTL/Arabic, dark mode, mobile and accessibility (WCAG 2.2 AA) as first-class. Hand the developer a concrete spec." },
  { key: "developer", title: "Developer", agent: "", type: "build", enabled: true, instruction: "Implement the requirements and the UI/UX spec with focused diffs, following the project's existing conventions. Address any feedback from the previous cycle." },
  { key: "qa", title: "QA Tester", agent: "", type: "check", enabled: true, instruction: "Test the implementation against every requirement. Set approved=false with the specific failing cases if anything fails." },
  { key: "browser", title: "Browser Tester", agent: "browser-tester", type: "check", enabled: true, instruction: "Drive the running app in a real browser through the user flows. Check rendering in RTL/dark/mobile, read console and network errors, screenshot each state. Set approved=false with the failing steps and screenshots if anything breaks." },
  { key: "reviewer", title: "Reviewer", agent: "", type: "check", enabled: true, instruction: "Review the implementation and the QA report for correctness and quality. Approve, or set approved=false and list the exact changes still needed." },
  { key: "signoff", title: "Sign-off (BA)", agent: "", type: "signoff", enabled: true, instruction: "Decide whether the delivered product meets the acceptance criteria. Approve for deploy, or set approved=false and say what is missing." },
];

const S = (s: string) => JSON.stringify(s || "");

function buildWorkflow(name: string, task: string, maxCycles: number, roles: Role[]): string {
  const on = roles.filter((r) => r.enabled && r.instruction.trim());
  const plan = on.filter((r) => r.type === "plan");
  const loop = on.filter((r) => r.type === "build" || r.type === "check");
  const signoff = on.filter((r) => r.type === "signoff");
  const mc = Math.max(1, Math.min(20, maxCycles | 0)) || 3;
  const at = (r: Role) => (r.agent ? `, agentType: ${S(r.agent)}` : "");

  const phaseTitles: string[] = [];
  if (plan.length) phaseTitles.push("Plan");
  if (loop.some((r) => r.type === "build")) phaseTitles.push("Build");
  if (loop.some((r) => r.type === "check")) phaseTitles.push("Review");
  if (signoff.length) phaseTitles.push("Sign-off");
  const titles = phaseTitles.length ? phaseTitles : ["Run"];

  let b = "";
  b += `export const meta = {\n`;
  b += `  name: ${S(name)},\n`;
  b += `  description: ${S("Team pipeline: " + (on.map((r) => r.title).join(" \u2192 ") || "(empty)"))},\n`;
  b += `  phases: [\n${titles.map((t) => `    { title: ${S(t)} },`).join("\n")}\n  ],\n`;
  b += `}\n\n`;
  b += `// Generated by Claude Control \u2014 Team builder.\n`;
  b += `// Run it in a Claude Code session in this project: open /workflows, or ask\n`;
  b += `// Claude to run the "${name}" workflow. Override the brief with args.task.\n\n`;
  b += `const TASK = (args && args.task) || ${S(task)}\n`;
  b += `const MAX_CYCLES = ${mc}\n`;
  b += `const GATE = { type: 'object', properties: { approved: { type: 'boolean' }, feedback: { type: 'string' } }, required: ['approved'] }\n\n`;
  b += `let context = "## Brief\\n" + TASK\n`;

  for (const r of plan) {
    b += `phase('Plan')\n`;
    b += `{ const out = await agent(${S(r.instruction)} + "\\n\\n" + context, { label: ${S(r.title)}, phase: 'Plan'${at(r)} }); context += "\\n\\n## " + ${S(r.title)} + "\\n" + out }\n`;
  }

  b += `\nlet cycle = 0, feedback = '', delivered = context, checksApproved = true\n`;
  if (loop.length) {
    b += `while (cycle < MAX_CYCLES) {\n`;
    b += `  cycle++\n`;
    b += `  let round = context + (feedback ? "\\n\\n## Address this feedback from the last cycle\\n" + feedback : '')\n`;
    b += `  const checks = []\n`;
    for (const r of loop) {
      if (r.type === "build") {
        b += `  phase('Build')\n`;
        b += `  { const out = await agent(${S(r.instruction)} + "\\n\\n" + round, { label: ${S(r.title)} + ': cycle ' + cycle, phase: 'Build'${at(r)} }); round += "\\n\\n## " + ${S(r.title)} + "\\n" + out }\n`;
      } else {
        b += `  phase('Review')\n`;
        b += `  { const v = await agent(${S(r.instruction)} + "\\n\\n" + round, { label: ${S(r.title)} + ': cycle ' + cycle, phase: 'Review'${at(r)}, schema: GATE }); round += "\\n\\n## " + ${S(r.title)} + " verdict\\n" + JSON.stringify(v); checks.push({ role: ${S(r.title)}, approved: !!v.approved, feedback: v.feedback || '' }) }\n`;
      }
    }
    b += `  delivered = round\n`;
    b += `  checksApproved = checks.length ? checks.every((c) => c.approved) : true\n`;
    b += `  if (checksApproved) { log('Cycle ' + cycle + ': approved by all checks.'); break }\n`;
    b += `  feedback = checks.filter((c) => !c.approved).map((c) => c.feedback).filter(Boolean).join('\\n')\n`;
    b += `  log('Cycle ' + cycle + ': changes requested \u2014 recycling.')\n`;
    b += `}\n`;
  }

  b += `\nconst signoffs = []\n`;
  for (const r of signoff) {
    b += `phase('Sign-off')\n`;
    b += `{ const v = await agent(${S(r.instruction)} + "\\n\\n## Context\\n" + context + "\\n\\n## Delivered\\n" + delivered + "\\n\\nApprove for deploy ONLY if the acceptance criteria are met; otherwise set approved false and explain what is missing.", { label: ${S(r.title)}, phase: 'Sign-off'${at(r)}, schema: GATE }); signoffs.push({ role: ${S(r.title)}, approved: !!v.approved, feedback: v.feedback || '' }) }\n`;
  }

  b += `\nreturn { task: TASK, cycles: cycle, checksApproved, approved: checksApproved && signoffs.every((s) => s.approved), signoffs }\n`;
  return b;
}

export function TeamPage() {
  const { toast } = useStore();
  const [projects, setProjects] = useState<Project[]>([]);
  const [proj, setProj] = useState<string>(""); // claudeDir of selected project ("" = global)
  const [agents, setAgents] = useState<Agent[]>([]);
  const [name, setName] = useState("product-team");
  const [task, setTask] = useState("");
  const [maxCycles, setMaxCycles] = useState(3);
  const [roles, setRoles] = useState<Role[]>(DEFAULT_ROLES.map((r) => ({ ...r })));
  const [script, setScript] = useState("");
  const [saving, setSaving] = useState(false);
  const [genRole, setGenRole] = useState<string | null>(null);
  const [flash, setFlash] = useState<string | null>(null);
  const [wfs, setWfs] = useState<{ name: string; description: string; path: string }[]>([]);
  const { confirm, node: confirmNode } = useConfirm();

  const pickRole = (key: string) => {
    document.getElementById("pg-role-" + key)?.scrollIntoView({ behavior: "smooth", block: "center" });
    setFlash(key);
    window.setTimeout(() => setFlash((f) => (f === key ? null : f)), 1200);
  };

  useEffect(() => { api.projects().then((r) => setProjects(r.projects)).catch(() => {}); }, []);
  useEffect(() => { api.listAgents().then((r) => setAgents(r.agents)).catch(() => {}); }, []);

  const loadWfs = useCallback(async () => {
    try { const r = await api.listWorkflows(proj || undefined); setWfs(r.workflows); } catch { setWfs([]); }
  }, [proj]);
  useEffect(() => { loadWfs(); }, [loadWfs]);

  const agentNames = useMemo(() => agents.map((a) => a.name), [agents]);
  const current = projects.find((p) => (p.isGlobal ? proj === "" : p.claudeDir === proj));

  const setRole = (i: number, patch: Partial<Role>) =>
    setRoles((rs) => rs.map((r, j) => (j === i ? { ...r, ...patch } : r)));
  const addRole = () =>
    setRoles((rs) => [...rs, { key: "custom-" + Date.now(), title: "New role", agent: "", instruction: "", enabled: true, type: "build" as RoleType }]);
  const removeRole = (i: number) => setRoles((rs) => rs.filter((_, j) => j !== i));
  const moveRole = (i: number, dir: -1 | 1) =>
    setRoles((rs) => {
      const j = i + dir;
      if (j < 0 || j >= rs.length) return rs;
      const next = rs.slice();
      [next[i], next[j]] = [next[j], next[i]];
      return next;
    });

  const missing = roles.filter((r) => r.enabled && (!r.agent || !agentNames.includes(r.agent)));

  const genAgent = async (i: number) => {
    const r = roles[i];
    setGenRole(r.key);
    try {
      const res = await api.generateAgent(r.title, r.instruction);
      if (!res.ok || !res.agent) { toast(res.message || "Generation failed", "err"); return; }
      await api.saveAgent(res.agent.name, res.agent);           // into the global roster
      const list = await api.listAgents(); setAgents(list.agents);
      setRole(i, { agent: res.agent.name });
      toast(`Generated teammate “${res.agent.name}” and assigned to ${r.title}`, "ok");
    } catch (e: any) { toast("Generate failed: " + (e.message || e), "err"); }
    finally { setGenRole(null); }
  };
  const genMissing = async () => {
    for (let i = 0; i < roles.length; i++) {
      if (roles[i].enabled && (!roles[i].agent || !agentNames.includes(roles[i].agent))) await genAgent(i);
    }
  };

  const delWf = async (name: string) => {
    if (!(await confirm(`Delete workflow “${name}”? A timestamped backup is written first, so it's recoverable.`, true))) return;
    try { await api.deleteWorkflow(name, proj || undefined); toast(`Deleted ${name}`, "ok"); loadWfs(); }
    catch (e: any) { toast("Delete failed: " + (e.message || e), "err"); }
  };

  const openWf = async (wfName: string) => {
    if (roles.some((r) => r.instruction !== (DEFAULT_ROLES.find((d) => d.key === r.key)?.instruction ?? r.instruction)) || task || script) {
      if (!(await confirm(`Open “${wfName}” for editing? This replaces what's currently in the builder.`, false))) return;
    }
    try {
      const r = await api.readWorkflow(wfName, proj || undefined);
      const m = r.meta;
      if (m && Array.isArray(m.roles)) {
        setName(m.name || wfName);
        setTask(m.task || "");
        setMaxCycles(m.maxCycles || 3);
        setRoles(m.roles.map((x: Role) => ({ ...x })));
        setScript(r.content);
        toast(`Opened “${wfName}” — edit the roles and Save to update it`, "ok");
      } else {
        setName(wfName);
        setScript(r.content);
        toast(`Opened “${wfName}” as raw script (no role model saved for it — the editor below is editable, but the Roles form wasn't restored)`, "ok");
      }
    } catch (e: any) { toast("Open failed: " + (e.message || e), "err"); }
  };

  const generate = () => {
    if (!/^[a-z0-9][a-z0-9_-]*$/.test(name)) { toast("Name must be a lowercase slug", "err"); return; }
    setScript(buildWorkflow(name, task, maxCycles, roles));
  };

  const save = async () => {
    if (!script) return;
    if (!/^[a-z0-9][a-z0-9_-]*$/.test(name)) { toast("Name must be a lowercase slug", "err"); return; }
    if (wfs.some((w) => w.name === name) &&
        !(await confirm(`A workflow named “${name}” already exists here — saving will overwrite it (the previous version is backed up first). To keep both, give this one a different name.`, true))) return;
    setSaving(true);
    try {
      const meta = { v: 1, name, task, maxCycles, roles };
      const r = await api.saveWorkflow(name, script, proj || undefined, meta);
      toast(`Saved to ${r.path}${r.backup ? " (previous backed up)" : ""}`, "ok");
      loadWfs();
    } catch (e: any) { toast("Save failed: " + (e.message || e), "err"); }
    finally { setSaving(false); }
  };

  return (
    <div className="main-inner" style={{ maxWidth: 960 }}>
      <div className="page-head">
        <h1>Team Pipeline</h1>
        <p>
          Assemble your roster into a software team that runs a product end to end — <b>Business Analyst → Requirements →
          Developer → QA → Reviewer</b>, recycling the build&nbsp;↔&nbsp;QA&nbsp;↔&nbsp;review loop until it passes and the analyst
          signs off. This generates a real Claude Code <b>Workflow</b>; run it in a session and <a href="#" onClick={(e) => e.preventDefault()} style={{ color: "var(--accent)", cursor: "default" }}>Who&rsquo;s Working</a> shows the phases live.
        </p>
      </div>

      <Card title="Pipeline">
        <div className="form-grid">
          <div className="field">
            <label>Save to project</label>
            <select className="scope-select" style={{ marginInlineStart: 0, width: "100%" }} value={proj} onChange={(e) => setProj(e.target.value)}>
              {projects.map((p) => (
                <option key={p.id} value={p.isGlobal ? "" : p.claudeDir}>{(p.isGlobal ? "● " : "  ") + p.label}</option>
              ))}
            </select>
          </div>
          <div className="field">
            <label>Workflow name <span style={{ color: "var(--muted)", fontWeight: 400 }}>— one file per name; rename to save a second team</span></label>
            <input className="input-sm mono" value={name} onChange={(e) => setName(e.target.value.toLowerCase())} placeholder="product-team" />
          </div>
        </div>
        <div className="field">
          <label>The brief <span style={{ color: "var(--muted)", fontWeight: 400 }}>— what the team should build (also overridable at run time via args.task)</span></label>
          <textarea rows={3} value={task} onChange={(e) => setTask(e.target.value)} placeholder="e.g. Add a leave-request approval flow to the HR module with manager + HR sign-off and a Slack notification." />
        </div>
        <div className="field" style={{ maxWidth: 220 }}>
          <label>Max build↔review cycles</label>
          <input type="number" min={1} max={20} className="input-sm" style={{ width: 90 }} value={maxCycles} onChange={(e) => setMaxCycles(parseInt(e.target.value, 10) || 1)} />
        </div>
      </Card>

      <Card title="Flow" sub="your pipeline as a graph — Plan → recycle loop → Sign-off · click a node to edit it">
        <PipelineGraph roles={roles} maxCycles={maxCycles} agentNames={agentNames} onPick={pickRole} />
      </Card>

      <Card
        title="Roles"
        sub="assign a teammate to each, or generate one with AI"
        right={missing.length > 0 ? (
          <button className="btn sm" disabled={genRole !== null} onClick={genMissing}>
            {genRole ? "Generating…" : `✦ Generate ${missing.length} missing`}
          </button>
        ) : undefined}
      >
        {roles.map((r, i) => {
          const needs = r.enabled && (!r.agent || !agentNames.includes(r.agent));
          return (
            <div key={r.key} id={"pg-role-" + r.key} className={"role-row" + (flash === r.key ? " flash" : "")} style={{ padding: "12px 10px", borderBottom: "1px solid var(--border)", opacity: r.enabled ? 1 : 0.5 }}>
              <div style={{ display: "flex", gap: 8, alignItems: "center", marginBottom: 8, flexWrap: "wrap" }}>
                <span style={{ display: "inline-flex", flexDirection: "column", lineHeight: 0.8, flexShrink: 0 }}>
                  <button className="btn ghost sm" style={{ padding: "0 5px", minWidth: 0, color: i === 0 ? "var(--border)" : "var(--muted)" }} disabled={i === 0} title="Move up" onClick={() => moveRole(i, -1)}>▲</button>
                  <button className="btn ghost sm" style={{ padding: "0 5px", minWidth: 0, color: i === roles.length - 1 ? "var(--border)" : "var(--muted)" }} disabled={i === roles.length - 1} title="Move down" onClick={() => moveRole(i, 1)}>▼</button>
                </span>
                <input type="checkbox" checked={r.enabled} onChange={(e) => setRole(i, { enabled: e.target.checked })} title="Include this role in the pipeline" style={{ width: 15, height: 15, flexShrink: 0 }} />
                <input className="input-sm" style={{ fontWeight: 600, width: 150 }} value={r.title} onChange={(e) => setRole(i, { title: e.target.value })} />
                <select className="scope-select" style={{ marginInlineStart: 0, width: 108 }} value={r.type} onChange={(e) => setRole(i, { type: e.target.value as RoleType })} title={ROLE_TYPES.find((t) => t.value === r.type)?.hint}>
                  {ROLE_TYPES.map((t) => <option key={t.value} value={t.value}>{t.label}</option>)}
                </select>
                <span style={{ color: "var(--muted)", fontSize: 12 }}>played by</span>
                <Select value={r.agent} options={agentNames} allowEmpty="(default worker)" onChange={(v) => setRole(i, { agent: v })} />
                {r.agent && !agentNames.includes(r.agent) && <span className="badge ask" style={{ fontSize: 10 }}>not created yet</span>}
                {needs && (
                  <button className="btn ghost sm" disabled={genRole !== null} onClick={() => genAgent(i)} title="AI-generate this teammate and add it to your roster">
                    {genRole === r.key ? "Generating…" : "✦ Generate"}
                  </button>
                )}
                <button className="btn ghost sm" style={{ marginInlineStart: "auto", color: "var(--muted)" }} title="Remove role" onClick={() => removeRole(i)}>×</button>
              </div>
              <textarea rows={2} value={r.instruction} onChange={(e) => setRole(i, { instruction: e.target.value })} style={{ fontSize: 12.5 }} placeholder="What this role does…" />
            </div>
          );
        })}
        <div style={{ paddingTop: 10, display: "flex", alignItems: "center", gap: 8, flexWrap: "wrap" }}>
          <button className="btn ghost sm" onClick={addRole}>+ Add role</button>
          <span style={{ color: "var(--muted)", fontSize: 11 }}>Flow: <b>Plan</b> → (<b>Build</b> ↔ <b>Check</b> loop, recycles until all checks pass) → <b>Sign-off</b>. Uncheck any you don&rsquo;t need.</span>
        </div>
      </Card>

      <div style={{ display: "flex", gap: 8, margin: "4px 0 14px" }}>
        <button className="btn primary" onClick={generate}>Generate workflow</button>
        {script && <button className="btn" disabled={saving} onClick={save}>{saving ? "Saving…" : "Save to .claude/workflows/"}</button>}
      </div>

      <Card
        title="Saved workflows"
        sub={`${current?.isGlobal ? "~/.claude" : (proj || "~/.claude")}/workflows`}
        right={<button className="btn ghost sm" onClick={loadWfs}>Refresh</button>}
      >
        {wfs.length === 0 ? (
          <div className="empty-state" style={{ padding: 18, fontSize: 12.5 }}>No workflows saved in this scope yet — generate one above.</div>
        ) : wfs.map((w) => (
          <div key={w.name} style={{ display: "flex", gap: 10, alignItems: "center", padding: "10px 0", borderBottom: "1px solid var(--border)" }}>
            <div style={{ flex: 1, minWidth: 0 }}>
              <div className="mono" style={{ fontWeight: 600, fontSize: 13 }}>{w.name}</div>
              <div style={{ fontSize: 11.5, color: "var(--muted)", overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }} title={w.path}>{w.description || w.path}</div>
            </div>
            <button className="btn ghost sm" title="Open this workflow back in the builder to edit it" onClick={() => openWf(w.name)}>Edit</button>
            <button
              className="btn ghost sm"
              title="Copy a prompt to run it in a Claude Code session"
              onClick={() => { navigator.clipboard?.writeText(`Run the ${w.name} workflow on: `).then(() => toast("Run prompt copied — paste it into a session and add your brief", "ok"), () => {}); }}
            >Copy run</button>
            <button className="btn danger sm" onClick={() => delWf(w.name)}>Delete</button>
          </div>
        ))}
      </Card>

      {script && (
        <Card
          title="Generated workflow"
          sub={`${name}.js`}
          right={<button className="btn ghost sm" onClick={() => { navigator.clipboard?.writeText(script).then(() => toast("Copied", "ok"), () => {}); }}>Copy</button>}
        >
          <textarea rows={18} className="mono" value={script} onChange={(e) => setScript(e.target.value)} spellCheck={false} style={{ fontSize: 11.5, lineHeight: 1.5 }} />
          <div className="hint" style={{ marginTop: 8 }}>
            Saves to <code className="mono">{current?.isGlobal ? "~/.claude" : (current?.claudeDir || proj || "~/.claude")}/workflows/{name}.js</code>.
            Then, in a Claude Code session in that project: open <code className="mono">/workflows</code>, or tell Claude to run the <b>{name}</b> workflow — pass a different brief with <code className="mono">args.task</code>. Review it before running; it fans out real subagents.
          </div>
        </Card>
      )}
      {confirmNode}
    </div>
  );
}
